# Generate the notices for the locked Windows executable (PowerShell 7).
[CmdletBinding()]
param(
    [string] $Out = (Join-Path $PSScriptRoot '../THIRD-PARTY-NOTICES'),
    [switch] $Offline
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$outPath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Out)
$root = Split-Path -Parent $PSScriptRoot
$target = 'x86_64-pc-windows-msvc'
$flags = @('--locked')
if ($Offline) { $flags += '--offline' }

# Review all alternatives, not just the first acceptable choice. Slash is Cargo's legacy OR.
$allowed = 'MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib', 'Unicode-3.0',
    'MPL-2.0', '0BSD', 'Unlicense', 'CC0-1.0', 'Unicode-DFS-2016', 'LicenseRef-Sublime-Text-Packages'
function Assert-License([string] $expression, [string] $label) {
    $tokens = [regex]::Matches($expression, '[A-Za-z0-9.-]+|[()/]|\S').Value
    $operand = $true
    $depth = 0
    foreach ($token in $tokens) {
        if ($operand -and $token -ceq '(') { $depth++; continue }
        if ($operand -and $token -cin $allowed) { $operand = $false; continue }
        if (-not $operand -and $token -cin @('AND', 'OR', '/')) { $operand = $true; continue }
        if (-not $operand -and $token -ceq ')' -and $depth -gt 0) { $depth--; continue }
        throw "$label uses an unsupported licence expression: $expression"
    }
    if ($operand -or $depth -ne 0) { throw "$label has a missing or invalid licence expression: $expression" }
}

Push-Location -LiteralPath $root
try {
    # Cargo applies the real target cfg and feature resolution. Exclude proc macros and their
    # subtrees unless a crate also has a normal, non-proc-macro path to the executable.
    $tree = & cargo tree @flags -p claude-switch '--edges=normal,no-proc-macro' --target $target --prefix none --no-dedupe --format '{p}'
    if ($LASTEXITCODE -ne 0) { throw "cargo tree failed ($LASTEXITCODE)." }
    $json = & cargo metadata @flags --format-version 1 --filter-platform $target
    if ($LASTEXITCODE -ne 0) { throw "cargo metadata failed ($LASTEXITCODE)." }
    $metadata = ConvertFrom-Json -InputObject ($json -join "`n")
} finally {
    Pop-Location
}

# These exact checkouts were reviewed for assets and have a repository-level MIT LICENSE,
# but their crate manifests omit the licence expression. New pins require another audit.
$reviewedGit = @(
    'git+https://github.com/Kaan88/markdown-shared-rs?rev=137121c6a0006ad524cffc40ef4d29410dcb332f#137121c6a0006ad524cffc40ef4d29410dcb332f'
    'git+https://github.com/Kaan88/markdown-shared-rs?rev=48eb3cefb17f5025f3ac418f7a01b31b7a914779#48eb3cefb17f5025f3ac418f7a01b31b7a914779'
    'git+https://github.com/Kaan88/markdown-viewer-rs?rev=01f67b2aba1a89e0e1ccfba5f423b1b8085a6b99#01f67b2aba1a89e0e1ccfba5f423b1b8085a6b99'
)
$packages = @(
    foreach ($line in ($tree | Sort-Object -Unique -CaseSensitive)) {
        if ($line -cnotmatch '^(\S+) v(\S+)(?: \((.+)\))?$') { throw "Unrecognized cargo tree row: $line" }
        $name, $version, $location = $Matches[1], $Matches[2], $Matches[3]
        $candidates = $metadata.packages | Where-Object { $_.name -ceq $name -and $_.version -ceq $version }
        $match = @(
            if ($location -cmatch '^(https?://.+#[a-f0-9]+)$') {
                $candidates | Where-Object { $_.source -clike "git+$location*" }
            } elseif ($location) {
                $candidates | Where-Object { -not $_.source -and (Split-Path $_.manifest_path) -eq $location }
            } else {
                $candidates | Where-Object { $_.source -clike 'registry+*' -or $_.source -clike 'sparse+*' }
            }
        )
        if ($match.Count -ne 1) { throw "Could not uniquely resolve cargo tree row: $line" }
        $match[0]
    }
)
if (-not $packages -or 'claude-switch' -cnotin $packages.name) { throw 'Executable missing from the inventory.' }

$lines = [Collections.Generic.List[string]]::new()
$texts = [Collections.Generic.List[string]]::new()
$index = [Collections.Generic.Dictionary[string, int]]::new([StringComparer]::Ordinal)
$utf8 = [Text.UTF8Encoding]::new($false, $true)

function Add-Notice([string] $source, [string] $path) {
    $text = [IO.File]::ReadAllText($path, $utf8).Replace("`r`n", "`n").Replace("`r", "`n").TrimEnd("`n")
    if ([string]::IsNullOrWhiteSpace($text)) { throw "Empty licence/notice: $path" }
    if (-not $index.ContainsKey($text)) {
        $texts.Add($text)
        $index.Add($text, $texts.Count)
    }
    $lines.Add("  $source -> text $($index[$text])")
}

$lines.AddRange([string[]]@(
    'Claude Switch | Third-party notices'
    "Generated by tools/write-third-party-notices.ps1 for $target."
    'Inventory: locked normal dependencies, excluding proc-macro, build and dev-only trees.'
    'Workspace crates are listed for completeness. Identical notice texts are printed once.'
    ''
    'Crates'
    '======'
))
foreach ($p in ($packages | Sort-Object name, version, source -CaseSensitive -Culture en-US)) {
    $label = "$($p.name) $($p.version)"
    $dir = Split-Path $p.manifest_path
    $licence = $p.license
    $fallback = $null
    if ($p.source -clike 'git+*') {
        if ($p.source -cnotin $reviewedGit) { throw "Unaudited git source: $($p.source)" }
        $rev = ($p.source -split '#')[-1]
        $checkout = [IO.DirectoryInfo]::new($dir)
        while ($checkout -and -not $rev.StartsWith($checkout.Name, [StringComparison]::Ordinal)) {
            $checkout = $checkout.Parent
        }
        if (-not $checkout) { throw "Cannot find pinned checkout for $label" }
        $fallback = Join-Path $checkout.FullName 'LICENSE'
        if (-not $licence) { $licence = 'MIT' }
    } elseif ($p.id -cin $metadata.workspace_members) {
        $fallback = Join-Path $root 'LICENSE'
    }
    Assert-License $licence $label
    $source = if ($p.source) { " ($($p.source))" } else { ' (Claude Switch workspace)' }
    $lines.Add('')
    $lines.Add("$label [$licence]$source")

    $files = @(Get-ChildItem -LiteralPath $dir -File | Where-Object {
        $_.Name -match '^(licen[sc]e|copying|notice|copyright|unlicense)([-_.]|$)'
    } | ForEach-Object FullName)
    if ($p.license_file) { $files += Join-Path $dir $p.license_file }
    # A NOTICE does not replace the workspace/checkout licence.
    if ($fallback) { $files += $fallback }
    if (-not ($p.license_file -or $fallback -or ($files | Where-Object {
        (Split-Path $_ -Leaf) -match '^(licen[sc]e|copying|unlicense)([-_.]|$)'
    }))) { throw "No licence text found for $label" }
    foreach ($file in ($files | Sort-Object -Unique -CaseSensitive -Culture en-US)) {
        $fileLabel = if ($file -eq $fallback) { 'Repository LICENSE' } else { [IO.Path]::GetRelativePath($dir, $file).Replace('\', '/') }
        Add-Notice $fileLabel $file
    }
    # Registry packages can carry additional notices beside vendored code or data.
    # The two current nested notices are Unicode tables and tracing-core's vendored spin lock.
    if ($p.source -clike 'registry+*' -or $p.source -clike 'sparse+*') {
        $nested = @(Get-ChildItem -LiteralPath $dir -Recurse -File | Where-Object {
            $_.DirectoryName -ne $dir -and $_.Name -match '^(licen[sc]e|copying|notice|copyright|unlicense)([-_.]|$)'
        } | Sort-Object FullName -CaseSensitive -Culture en-US)
        foreach ($file in $nested) {
            $fileLabel = [IO.Path]::GetRelativePath($dir, $file.FullName).Replace('\', '/')
            $nestedLicence = switch -CaseSensitive ("$($p.name)/$fileLabel") {
                'regex-syntax/src/unicode_tables/LICENSE-UNICODE' { 'Unicode-DFS-2016' }
                'tracing-core/src/spin/LICENSE' { 'MIT' }
                default { throw "Unaudited nested licence/notice for $label`: $fileLabel" }
            }
            Assert-License $nestedLicence "$label $fileLabel"
            Add-Notice "$fileLabel [$nestedLicence]" $file.FullName
        }
    }
}

$lines.AddRange([string[]]@(
    ''
    'Bundled assets'
    '=============='
    'The reviewed markdown-shared-rs and markdown-viewer-rs checkouts use installed Windows'
    'fonts, not bundled font files. The viewer icon and fixtures are not part of these libraries'
    'in Claude Switch. The toolkit highlighter loads the embedded Syntect syntax/theme packs.'
))
$syntect = @($packages | Where-Object name -ceq 'syntect')
if ($syntect.Count -ne 1 -or $syntect[0].version -cne '5.3.0') { throw 'Re-audit the syntax/theme packs for this Syntect version.' }
$assetList = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'notice-assets/syntect-5.3.0.json') -Raw | ConvertFrom-Json
foreach ($pack in $assetList.packs) {
    $path = Join-Path (Split-Path $syntect[0].manifest_path) "assets/$($pack.file)"
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -ne $pack.sha256) {
        throw "Syntect asset changed: $($pack.file)"
    }
}
foreach ($asset in $assetList.notices) {
    Assert-License $asset.license $asset.name
    $lines.Add('')
    $lines.Add("$($asset.name) [$($asset.license)]")
    Add-Notice $asset.source (Join-Path $PSScriptRoot "notice-assets/$($asset.file)")
}

$lines.AddRange([string[]]@('', 'Licence and notice texts', '========================'))
for ($i = 0; $i -lt $texts.Count; $i++) {
    $lines.AddRange([string[]]@('', "----- text $($i + 1) -----", $texts[$i]))
}
[void][IO.Directory]::CreateDirectory((Split-Path -Parent $outPath))
[IO.File]::WriteAllText($outPath, ($lines -join "`n") + "`n", $utf8)
Write-Host "Wrote $($packages.Count) crates and $($assetList.notices.Count) asset notices to $outPath."
